#!/usr/bin/env node
// Builds ONE self-contained index.html: src/template.html + the bundled app (with the pixelfx code it uses inlined).
//   node build.mjs
// Needs the pixelfx checkout next to this file (git clone https://github.com/patch-gg/pixelfx) and its pinned esbuild
// (cd pixelfx && npm ci). The site itself has no build step at runtime: index.html is the deliverable.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL, fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";
import { COPY } from "./src/copy.js";

const ROOT = dirname(fileURLToPath(import.meta.url));
const PFX = join(ROOT, "pixelfx");
const require = createRequire(join(PFX, "package.json"));
const { build } = require("esbuild");

const read = (p) => readFileSync(p, "utf8");

// ---- licenses and the list of effects used (fed to the credits page and the HTML comment) ----
const MIT = read(join(PFX, "LICENSE")).trim();
const NOTICE = read(join(PFX, "NOTICE.md")).trim();
const fxSrc = read(join(ROOT, "src/fx.js"));
const used = [...fxSrc.matchAll(/^\s+"([a-z-]+\/[a-z-]+)": \w+,$/gm)].map((m) => m[1]);
const effects = [];
for (const id of used) {
  const mod = await import(pathToFileURL(join(PFX, "src/fx", `${id}.js`)).href);
  effects.push({ id, name: mod.meta.name });
}
writeFileSync(join(ROOT, "src/licenses.generated.js"),
  `// Generated by build.mjs from pixelfx/LICENSE and pixelfx/NOTICE.md. Do not edit.\n` +
  `export const MIT_TEXT = ${JSON.stringify(MIT)};\nexport const NOTICE_TEXT = ${JSON.stringify(NOTICE)};\n` +
  `export const EFFECTS_USED = ${JSON.stringify(effects)};\n`);

// ---- bundle ----
const result = await build({
  entryPoints: [join(ROOT, "src/app.js")],
  bundle: true,
  format: "esm",
  target: "es2022",
  write: false,
  external: ["three"], // loaded by the importmap, dynamically, so a CDN failure never blanks the page
  treeShaking: true,   // only the pixelfx code the effect map actually reaches is shipped
  legalComments: "inline",
  metafile: true,
  logLevel: "warning",
});
let js = result.outputFiles[0].text;

// attribution comments: esbuild drops ordinary comments, so each embedded pixelfx file's leading comment block is
// copied verbatim above the bundle
const pfxFiles = Object.keys(result.metafile.inputs).filter((f) => f.startsWith("pixelfx/src/")).sort();
const attributions = pfxFiles.map((f) => {
  const lines = [];
  for (const line of read(join(ROOT, f)).split("\n")) {
    if (line.startsWith("//")) lines.push(line.replace(/\*\//g, "* /"));
    else if (line.trim() === "" && !lines.length) continue;
    else break;
  }
  return lines.length ? `/* ${f}\n${lines.join("\n")}\n*/` : null;
}).filter(Boolean);
js = `/* pixelfx (MIT) is embedded below: ${pfxFiles.length} files. Attribution comments from each file, unchanged:\n*/\n${attributions.join("\n")}\n` + js;
js = js.replace("/*! INTRO:START */", "/* INTRO:START */").replace("/*! INTRO:END */", "/* INTRO:END */");
js = js.replace(/<\/script/gi, "<\\/script");

// ---- html ----
const svg = readFileSync(join(ROOT, "logo.svg"));
const favicon = `data:image/svg+xml;base64,${svg.toString("base64")}`;
const esc = (s) => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const comment = `<!--\nThe pixel effects in this page come from pixelfx by Patch (https://github.com/patch-gg/pixelfx), MIT License,\nwhich adapts Sprite Fusion's open-source VFX by Hugo Duprez and Hollow Crown's skill playback code.\nLOOT is an independent project and is not affiliated with or endorsed by any of them.\n\n${MIT.replace(/--/g, "- -")}\n\nNOTICE.md\n\n${NOTICE.replace(/--/g, "- -")}\n-->`;
let page = read(join(ROOT, "src/template.html"));
const fill = {
  "{{TITLE}}": esc(COPY.meta.title),
  "{{DESC}}": esc(COPY.meta.description),
  "{{OG_TITLE}}": esc(COPY.meta.ogTitle),
  "{{OG_DESC}}": esc(COPY.meta.ogDescription),
  "{{NOSCRIPT}}": esc(COPY.meta.noscript),
  "{{FAVICON}}": favicon,
  "{{LICENSE_COMMENT}}": comment,
  "{{BUNDLE}}": js,
};
for (const [k, v] of Object.entries(fill)) page = page.split(k).join(v === js ? "\u0000BUNDLE\u0000" : v);
page = page.replace("\u0000BUNDLE\u0000", () => js);
writeFileSync(join(ROOT, "index.html"), page);
console.log(`index.html  ${(page.length / 1024).toFixed(0)} KB  (${pfxFiles.length} pixelfx files embedded: ${effects.length} effects)`);
